"""Audit SonArcan neural networks before lowering them to ExecuTorch.

By default this script stops at ``torch.export``, the common backend-independent
contract required by ExecuTorch. Setting ``SONARCAN_EXECUTORCH_BACKEND`` to
``portable``, ``xnnpack``, or ``coreml`` additionally lowers real checkpoints
and writes optional PTE artifacts for release-builder qualification.

The checkpoints remain external release inputs.  Nothing generated by this
script is bundled in the desktop application.
"""

